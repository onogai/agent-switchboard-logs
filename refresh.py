#!/usr/bin/env python3
"""Generate Vector file sources for selected Compose projects.

Runs on the Docker host under the operator's account. Vector itself never uses
the Docker API or socket. Only non-secret inspect fields are requested.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import time


PROJECTS = tuple(
    project.strip() for project in os.environ.get("LOGGING_COMPOSE_PROJECTS", "").split(",")
    if project.strip()
)
CONTAINERS_DIR = Path(os.environ.get("DOCKER_CONTAINERS_DIR", "/var/lib/docker/containers"))
OUTPUT = Path(__file__).parent / "generated" / "vector.toml"
INSPECT_FORMAT = (
    '{{.Id}}\t{{.Name}}\t{{.HostConfig.LogConfig.Type}}\t{{.LogPath}}\t'
    '{{index .Config.Labels "com.docker.compose.project"}}\t'
    '{{index .Config.Labels "com.docker.compose.service"}}'
)
ID_RE = re.compile(r"^[0-9a-f]{64}$")


def docker(*args: str) -> str:
    result = subprocess.run(
        ["docker", *args], capture_output=True, text=True, check=True, timeout=30
    )
    return result.stdout


def discover() -> list[dict[str, str]]:
    if not PROJECTS:
        raise RuntimeError("LOGGING_COMPOSE_PROJECTS must list at least one Compose project")
    ids: set[str] = set()
    for project in PROJECTS:
        ids.update(docker("ps", "-aq", "--filter", f"label=com.docker.compose.project={project}").split())
    if not ids:
        raise RuntimeError("No containers found in the selected Compose projects")
    rows = docker("inspect", "--format", INSPECT_FORMAT, *sorted(ids)).splitlines()
    containers: list[dict[str, str]] = []
    for row in rows:
        fields = row.split("\t")
        if len(fields) != 6:
            raise ValueError(f"Unexpected docker inspect output: {row!r}")
        cid, name, driver, path, project, service = fields
        if project not in PROJECTS:
            continue
        if driver != "json-file":
            raise ValueError(f"{name} uses {driver}, expected json-file")
        if not ID_RE.fullmatch(cid):
            raise ValueError(f"Invalid container ID for {name}")
        expected = CONTAINERS_DIR / cid / f"{cid}-json.log"
        if path != str(expected):
            raise ValueError(f"Unexpected log path for {name}: {path}")
        if not service or service == "<no value>":
            raise ValueError(f"Missing Compose service label for {name}")
        containers.append(
            {"id": cid, "name": name.removeprefix("/"), "path": path,
             "project": project, "service": service}
        )
    if not containers:
        raise RuntimeError("No eligible json-file containers found")
    return sorted(containers, key=lambda c: (c["project"], c["service"], c["id"]))


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(containers: list[dict[str, str]], host: str) -> str:
    lines = [
        '# Generated by refresh.py. Do not edit by hand.',
        'data_dir = "/var/lib/vector"',
        '',
    ]
    transform_ids = []
    for item in containers:
        cid = item["id"]
        source = f"docker_{cid}"
        transform = f"normalize_{cid}"
        transform_ids.append(transform)
        program = "\n".join(
            [
                "entry = parse_json!(.message)",
                ".message = string!(entry.log)",
                ".docker_time = string!(entry.time)",
                ".stream = string!(entry.stream)",
                f'.host = {quoted(host)}',
                f'.project = {quoted(item["project"])}',
                f'.service = {quoted(item["service"])}',
                f'.container_id = {quoted(cid)}',
                f'.container_name = {quoted(item["name"])}',
            ]
        )
        lines.extend(
            [
                f"[sources.{source}]",
                'type = "file"',
                # Include rotated files for a restart during Docker rotation.
                f'include = [{quoted(item["path"])}, {quoted(item["path"] + ".*")}]',
                'read_from = "beginning"',
                'fingerprint.strategy = "device_and_inode"',
                'file_key = ""',
                'host_key = ""',
                'max_line_bytes = 1048576',
                '',
                f"[transforms.{transform}]",
                'type = "remap"',
                f'inputs = [{quoted(source)}]',
                'drop_on_error = true',
                f"source = {quoted(program)}",
                '',
            ]
        )
    lines.extend(
        [
            '[sinks.victorialogs]',
            'type = "http"',
            f'inputs = [{", ".join(quoted(item) for item in transform_ids)}]',
            'uri = "http://victorialogs:9428/insert/jsonline?_stream_fields=host,project,service&_msg_field=message&_time_field=docker_time"',
            'compression = "gzip"',
            '',
            '[sinks.victorialogs.encoding]',
            'codec = "json"',
            '',
            '[sinks.victorialogs.framing]',
            'method = "newline_delimited"',
            '',
            '[sinks.victorialogs.healthcheck]',
            'enabled = false',
            '',
            '[sinks.victorialogs.buffer]',
            'type = "memory"',
            'max_events = 1000',
            'when_full = "drop_newest"',
            '',
        ]
    )
    return "\n".join(lines)


def refresh() -> bool:
    containers = discover()
    host = os.uname().nodename
    rendered = render(containers, host)
    OUTPUT.parent.mkdir(mode=0o755, exist_ok=True)
    os.chmod(OUTPUT.parent, 0o755)
    if OUTPUT.exists() and OUTPUT.read_text(encoding="utf-8") == rendered:
        return False
    temp = OUTPUT.with_suffix(".toml.tmp")
    temp.write_text(rendered, encoding="utf-8")
    # Vector runs as root with all capabilities dropped. It must still be able
    # to traverse this bind-mounted directory owned by the host account.
    os.chmod(temp, 0o644)
    temp.replace(OUTPUT)
    print(f"Updated Vector sources for {len(containers)} containers", flush=True)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--watch", action="store_true", help="refresh after every interval")
    parser.add_argument("--interval", type=int, default=30, help="watch interval in seconds")
    args = parser.parse_args()
    if args.interval < 5:
        parser.error("--interval must be at least 5 seconds")
    if not args.watch:
        refresh()
        return 0
    while True:
        try:
            refresh()
        except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as error:
            print(f"Source refresh failed; retaining the last configuration: {error}", file=sys.stderr, flush=True)
        time.sleep(args.interval)


if __name__ == "__main__":
    raise SystemExit(main())
